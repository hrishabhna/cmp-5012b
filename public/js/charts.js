 
async function get(url) {
  return fetch(url).then(r => r.json());
}
 
function label(dateStr) {
  return new Date(dateStr + 'T00:00:00').toLocaleDateString('en-GB', { day: 'numeric', month: 'short' }); //this converts the date string into a simpler version
}
 
//this creates the chart where you can choose from either a line or a bar and the data can be inserted. The bars are rounded in  the corners and the lines will become a smooth curve.
function makeChart(container, type, labels, values, color) {
  const canvas = document.createElement('canvas');
  document.getElementById(container).appendChild(canvas);
  new Chart(canvas, {
    type,
    data: {
      labels,
      datasets: [{
        data: values,
        borderColor: color,
        backgroundColor: color.replace(')', ', 0.15)').replace('rgb', 'rgba'),//this changes the color to a more transparent version for the background of the bars.
        borderWidth: 2,
        borderRadius: type === 'bar' ? 4 : 0, //this rounds the corners of the bars if the chart type is bar, otherwise it sets the border radius to 0 for line charts.
        tension: 0.4,
        fill: type === 'line',
        pointRadius: type === 'line' ? 4 : 0,
      }]
    },
    options: {
      responsive: true,
      plugins: { legend: { display: false } },//this hides the legend of the chart since there is only one dataset and the color already indicates what it represents.
      scales: { x: { display: false }, y: { beginAtZero: true } }
    }
  });
}
 //This function fetches the weight, calories and excercise data and then draws the chart for each individual section. Each section is colour corordinated with weight being green, calories being blue and excercise is pink. 
async function loadCharts() {
  const weight   = await get('/api/dashboard/weight');
  const calories = await get('/api/dashboard/calories');//this fetches the calories data from the server using the get function and waits for the response before proceeding.
  const exercise = await get('/api/dashboard/exercise');
 
  // Weight
  if (weight.length)
    makeChart('chart-weight', 'line', weight.map(d => label(d.date)), weight.map(d => d.value), 'rgb(74, 222, 128)');//this checks if there is any weight data available, and if so, it calls the makeChart function to create a line chart in the container with the ID 'chart-weight'. The labels for the x-axis are generated by mapping the date of each weight entry through the label function, and the values for the y-axis are extracted from the weight data. The color of the line is set to a shade of green.
 
  // Calories
  if (calories.length)
    makeChart('cal-chart', 'bar', calories.map(d => label(d.date)), calories.map(d => d.value), 'rgb(96, 165, 250)');
 
  // Exercise 
  if (exercise.length)
    makeChart('ex-chart', 'bar', exercise.map(d => label(d.date)), exercise.map(d => d.value), 'rgb(244, 114, 182)');
}
 
document.addEventListener('DOMContentLoaded', loadCharts);